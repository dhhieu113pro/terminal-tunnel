/// Limits so an anonymous caller (e.g. through a public tunnel) cannot grow memory without bound.
const MAX_ROOMS: usize = 64;
const HOST_ROOM_TTL: Duration = Duration::from_secs(10 * 60);
const CLIENT_TTL: Duration = Duration::from_secs(2 * 60);
/// Idle limit once host and client are paired (the page pings every 20 s while open).
const SESSION_IDLE: Duration = Duration::from_secs(30 * 60);

// ------------------------------------------------------------ signaling server

#[derive(Default)]
struct Room {
    host: Option<mpsc::UnboundedSender<Message>>,
    client: Option<mpsc::UnboundedSender<Message>>,
}
type Rooms = Arc<Mutex<HashMap<String, Room>>>;

/// Adds browser hardening headers to every response. No third-party sources are allowed.
async fn security_headers(req: Request, next: Next) -> Response {
    let mut res = next.run(req).await;
    let h = res.headers_mut();
    for (k, v) in [
        (
            header::CONTENT_SECURITY_POLICY,
            "default-src 'none'; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline'; \
             connect-src 'self' ws: wss:; img-src 'self' data:; base-uri 'none'; form-action 'none'; \
             frame-ancestors 'none'",
        ),
        (header::REFERRER_POLICY, "no-referrer"),
        (header::X_CONTENT_TYPE_OPTIONS, "nosniff"),
        (header::X_FRAME_OPTIONS, "DENY"),
        (header::CACHE_CONTROL, "no-store"),
    ] {
        h.insert(k, HeaderValue::from_static(v));
    }
    res
}

fn asset(content_type: &'static str, body: &'static str) -> impl IntoResponse {
    ([(header::CONTENT_TYPE, content_type)], body)
}

/// Run the relay on `bind` (an IP address). Loopback is the safe choice: a tunnel or an https reverse
/// proxy on the same machine reaches it, and Windows Firewall never asks about loopback listeners.
pub async fn run_signal(port: u16, bind: &str) -> Result<()> {
    let app = Router::new()
        .route("/", get(|| async { "terminal-tunnel signaling server" }))
        .route("/w/{room}", get(|| async { Html(INDEX) }))
        .route("/static/xterm.min.js", get(|| async { asset("text/javascript; charset=utf-8", XTERM_JS) }))
        .route("/static/xterm-addon-fit.min.js", get(|| async { asset("text/javascript; charset=utf-8", XTERM_FIT_JS) }))
        .route("/static/xterm.min.css", get(|| async { asset("text/css; charset=utf-8", XTERM_CSS) }))
        .route("/favicon.ico", get(|| async { ([(header::CONTENT_TYPE, "image/x-icon")], ICON_ICO) }))
        .route("/icon-180.png", get(|| async { ([(header::CONTENT_TYPE, "image/png")], ICON_180) }))
        .route("/ws/{room}/{role}", get(ws_handler))
        .layer(middleware::from_fn(security_headers))
        .with_state(Rooms::default());
    let addr = bind;
    let listener = tokio::net::TcpListener::bind((addr, port))
        .await
        .with_context(|| format!("cannot bind {addr}:{port}"))?;
    axum::serve(listener, app).await?;
    Ok(())
}

async fn ws_handler(
    ws: WebSocketUpgrade,
    Path((room, role)): Path<(String, String)>,
    State(rooms): State<Rooms>,
) -> Response {
    let is_host = match role.as_str() {
        "host" => true,
        "client" => false,
        _ => return StatusCode::BAD_REQUEST.into_response(),
    };
    if room.is_empty() || room.len() > 64 {
        return StatusCode::BAD_REQUEST.into_response();
    }
    ws.max_message_size(64 * 1024).on_upgrade(move |s| relay(s, rooms, room, is_host))
}

/// Pairs one host with exactly one client per room and forwards text and binary messages between
/// them. The frames are end-to-end encrypted, so the relay never sees plaintext terminal data.
async fn relay(sock: WebSocket, rooms: Rooms, room: String, is_host: bool) {
    let (mut tx, mut rx) = sock.split();
    let (my_tx, mut my_rx) = mpsc::unbounded_channel::<Message>();
    // Why this connection was refused, if it was (sent to the peer as the WebSocket close reason).
    let rejected: Option<&'static str> = {
        let mut g = rooms.lock().unwrap();
        if is_host {
            if g.contains_key(&room) || g.len() >= MAX_ROOMS {
                Some("room unavailable") // cannot hijack an existing room; bounded memory
            } else {
                g.insert(room.clone(), Room { host: Some(my_tx), client: None });
                None
            }
        } else {
            match g.get_mut(&room) {
                None => Some("no host is waiting for this link (it expired, the host stopped, or the link is wrong)"),
                Some(r) if r.client.is_some() => Some("link already used (single-use): restart host-web and rescan"),
                Some(r) => {
                    r.client = Some(my_tx); // stays taken: single-use
                    None
                }
            }
        }
    };
    if let Some(reason) = rejected {
        let _ = tx.send(Message::Close(Some(CloseFrame { code: 4000, reason: reason.into() }))).await;
        return;
    }
    let writer = tokio::spawn(async move {
        while let Some(m) = my_rx.recv().await {
            if tx.send(m).await.is_err() {
                break;
            }
        }
    });
    loop {
        // Drop idle/abandoned connections so rooms are freed: short while waiting for the other
        // side, long once paired.
        let paired = rooms
            .lock()
            .unwrap()
            .get(&room)
            .is_some_and(|r| r.host.is_some() && r.client.is_some());
        let idle = if paired { SESSION_IDLE } else if is_host { HOST_ROOM_TTL } else { CLIENT_TTL };
        let Ok(Some(Ok(msg))) = tokio::time::timeout(idle, rx.next()).await else { break };
        match msg {
            Message::Text(_) | Message::Binary(_) => {
                let g = rooms.lock().unwrap();
                if let Some(r) = g.get(&room) {
                    let peer = if is_host { &r.client } else { &r.host };
                    if let Some(p) = peer {
                        let _ = p.send(msg);
                    }
                }
            }
            Message::Close(_) => break,
            _ => {} // ping/pong are answered by the server
        }
    }
    // Tell the other side this one is gone.
    if let Some(r) = rooms.lock().unwrap().get(&room) {
        let peer = if is_host { &r.client } else { &r.host };
        if let Some(p) = peer {
            let _ = p.send(Message::Text(r#"{"t":"peer-left"}"#.into()));
        }
    }
    writer.abort();
    if is_host {
        rooms.lock().unwrap().remove(&room);
    }
}

// ------------------------------------------------------------ host

fn rand_hex(n: usize) -> Result<String> {
    let mut b = vec![0u8; n];
    getrandom::fill(&mut b).map_err(|e| anyhow!("rng: {e}"))?;
    Ok(hex::encode(b))
}

fn print_qr(url: &str) -> Result<()> {
    use qrcode::{QrCode, render::unicode};
    let code = QrCode::new(url.as_bytes())?;
    let img = code.render::<unicode::Dense1x2>().quiet_zone(true).build();
    println!("{img}");
    Ok(())
}

/// 6-digit code both sides display so a human can eyeball that they are on the same connection
/// (e.g. "042 917"). Derived from the token and both handshake nonces; the page computes the same.
fn match_code(token: &str, transcript: &str) -> String {
    let b = new_mac(token, "sas", transcript).finalize().into_bytes();
    let n = u32::from_be_bytes([b[0], b[1], b[2], b[3]]) % 1_000_000;
    format!("{:03} {:03}", n / 1000, n % 1000)
}

fn new_mac(token: &str, label: &str, transcript: &str) -> Hmac<Sha256> {
    let mut m = Hmac::<Sha256>::new_from_slice(token.as_bytes()).expect("hmac accepts any key length");
    m.update(label.as_bytes());
    m.update(b"|");
    m.update(transcript.as_bytes());
    m
}

// ------------------------------------------------------------ encrypted terminal session
//
// The terminal travels over the relay WebSocket (through the Dev Tunnel), and every frame is
// AES-256-GCM encrypted with keys derived from the token. The token lives only in the URL fragment,
// so the tunnel relay and the relay server only ever see ciphertext.
//
//   phone -> host  text   {"t":"hello","n":<16 random bytes hex>}
//   host  -> phone text   {"t":"hello","n":<16 random bytes hex>,"p":<HMAC proof of the token>}
//   keys: HKDF-SHA256(ikm = token, salt = clientNonce || hostNonce, info = "tt-ws-1 c2h" | "tt-ws-1 h2c")
//   frame (binary): [counter u64 BE][AES-GCM(ciphertext || tag)], nonce = [0,0,0,dir] || counter,
//   dir 1 = phone->host, 2 = host->phone; counters must arrive strictly in order (no replay/reorder).
//   plaintext: [type u8][data]
//     phone -> host: 0 = authenticated (host starts the shell), 1 = input, 2 = resize(cols,rows u16 BE), 3 = ping
//     host -> phone: 1 = output, 3 = pong, 4 = shell exited

const WS_AAD: &[u8] = b"tt-ws-1";
const DIR_C2H: u8 = 1;
const DIR_H2C: u8 = 2;

/// HKDF-SHA256 (RFC 5869), first 32 bytes of output.
fn hkdf32(ikm: &[u8], salt: &[u8], info: &[u8]) -> [u8; 32] {
    let mut m = Hmac::<Sha256>::new_from_slice(salt).expect("hmac accepts any key length");
    m.update(ikm);
    let prk = m.finalize().into_bytes();
    let mut m = Hmac::<Sha256>::new_from_slice(&prk).expect("hmac accepts any key length");
    m.update(info);
    m.update(&[1]);
    let mut out = [0u8; 32];
    out.copy_from_slice(&m.finalize().into_bytes());
    out
}

struct Crypt {
    enc: Aes256Gcm,
    dec: Aes256Gcm,
    send_dir: u8,
    recv_dir: u8,
    send_ctr: u64,
    recv_ctr: u64,
}

fn nonce_for(dir: u8, ctr: u64) -> [u8; 12] {
    let mut n = [0u8; 12];
    n[3] = dir;
    n[4..].copy_from_slice(&ctr.to_be_bytes());
    n
}

impl Crypt {
    fn new(token: &str, client_nonce: &[u8], host_nonce: &[u8], is_host: bool) -> Result<Self> {
        let salt = [client_nonce, host_nonce].concat();
        let c2h = hkdf32(token.as_bytes(), &salt, b"tt-ws-1 c2h");
        let h2c = hkdf32(token.as_bytes(), &salt, b"tt-ws-1 h2c");
        let cipher = |k: &[u8; 32]| Aes256Gcm::new_from_slice(k).map_err(|e| anyhow!("cipher: {e}"));
        let (enc, dec, send_dir, recv_dir) = if is_host {
            (cipher(&h2c)?, cipher(&c2h)?, DIR_H2C, DIR_C2H)
        } else {
            (cipher(&c2h)?, cipher(&h2c)?, DIR_C2H, DIR_H2C)
        };
        Ok(Self { enc, dec, send_dir, recv_dir, send_ctr: 0, recv_ctr: 0 })
    }

    fn seal(&mut self, plain: &[u8]) -> Result<Vec<u8>> {
        let ctr = self.send_ctr;
        self.send_ctr += 1;
        let nonce = nonce_for(self.send_dir, ctr);
        let ct = self
            .enc
            .encrypt((&nonce).into(), Payload { msg: plain, aad: WS_AAD })
            .map_err(|_| anyhow!("encrypt failed"))?;
        let mut frame = ctr.to_be_bytes().to_vec();
        frame.extend_from_slice(&ct);
        Ok(frame)
    }

    fn open(&mut self, frame: &[u8]) -> Result<Vec<u8>> {
        if frame.len() < 8 + 16 {
            bail!("frame too short");
        }
        let ctr = u64::from_be_bytes(frame[..8].try_into().unwrap());
        if ctr != self.recv_ctr {
            bail!("unexpected frame counter (replayed or reordered)");
        }
        let nonce = nonce_for(self.recv_dir, ctr);
        let plain = self
            .dec
            .decrypt((&nonce).into(), Payload { msg: &frame[8..], aad: WS_AAD })
            .map_err(|_| anyhow!("decryption failed (wrong token or tampered data)"))?;
        self.recv_ctr += 1;
        Ok(plain)
    }
}

type HostWs = tokio_tungstenite::WebSocketStream<tokio_tungstenite::MaybeTlsStream<tokio::net::TcpStream>>;

/// Host side of the WebSocket transport: handshake, then shell I/O as encrypted frames.
/// Progress of a session, for a UI (the tray) that wants more than the console messages.
#[derive(Debug)]
pub enum SessionEvent {
    /// The phone proved the token and the shell started; `code` is the match code to compare.
    Authenticated { code: String },
}

async fn ws_session(
    ws: HostWs,
    token: &str,
    shell: &str,
    root: Option<&std::path::Path>,
    events: Option<mpsc::UnboundedSender<SessionEvent>>,
    pty: &mut Option<Pty>,
) -> Result<()> {
    let r = ws_session_inner(ws, token, shell, root, events, pty).await;
    // The shell outlives the connection (like tmux/Termux): only output delivery stops.
    if let Some(p) = pty.as_mut() {
        p.detach();
    }
    r
}

async fn ws_session_inner(
    ws: HostWs,
    token: &str,
    shell: &str,
    root: Option<&std::path::Path>,
    events: Option<mpsc::UnboundedSender<SessionEvent>>,
    pty: &mut Option<Pty>,
) -> Result<()> {
    let (mut wtx, mut wrx) = ws.split();

    // 1. wait for the phone's hello
    let client_nonce = loop {
        match wrx.next().await {
            Some(Ok(WsMsg::Text(t))) => {
                let v: serde_json::Value = serde_json::from_str(t.as_str()).unwrap_or_default();
                if v["t"] == "hello" {
                    let n = hex::decode(v["n"].as_str().unwrap_or("")).unwrap_or_default();
                    if n.len() != 16 {
                        bail!("bad hello from the browser");
                    }
                    break n;
                }
            }
            Some(Ok(_)) => {}
            _ => bail!("signaling connection closed"),
        }
    };

    // 2. answer with our nonce and a proof that we know the token
    let mut host_nonce = [0u8; 16];
    getrandom::fill(&mut host_nonce).map_err(|e| anyhow!("rng: {e}"))?;
    let transcript = format!("{}|{}", hex::encode(&client_nonce), hex::encode(host_nonce));
    let proof = new_mac(token, "host", &transcript).finalize().into_bytes();
    let hello = serde_json::json!({ "t": "hello", "n": hex::encode(host_nonce), "p": hex::encode(proof) });
    wtx.send(WsMsg::Text(hello.to_string().into())).await?;
    let mut crypt = Crypt::new(token, &client_nonce, &host_nonce, true)?;

    // 3. encrypted session; the shell starts only after the first frame decrypts (proves the token)
    let mut attached = false;
    loop {
        let out = async {
            match pty.as_mut() {
                Some(p) if attached => p.out.recv().await,
                _ => std::future::pending().await,
            }
        };
        tokio::select! {
            msg = wrx.next() => match msg {
                Some(Ok(WsMsg::Binary(b))) => {
                    let plain = crypt.open(&b)?; // any failure ends the session
                    let Some((&kind, data)) = plain.split_first() else { continue };
                    match (kind, pty.as_mut().filter(|_| attached)) {
                        (0, None) => {
                            let code = match_code(token, &transcript);
                            eprintln!("browser authenticated (WebSocket, end-to-end encrypted)");
                            eprintln!("match code: {code}  (must be the same on the phone; if not, close the session)");
                            if let Some(tx) = &events {
                                let _ = tx.send(SessionEvent::Authenticated { code });
                            }
                            if pty.as_mut().is_some_and(|p| p.is_alive()) {
                                // reconnect: same shell, redraw what it showed
                                let screen = pty.as_mut().unwrap().attach();
                                if !screen.is_empty() {
                                    let mut plain = vec![1u8];
                                    plain.extend_from_slice(&screen);
                                    let f = crypt.seal(&plain)?;
                                    wtx.send(WsMsg::Binary(bytes::Bytes::from(f))).await?;
                                }
                            } else {
                                let mut p = Pty::spawn(shell, root)?;
                                p.attach();
                                *pty = Some(p);
                            }
                            attached = true;
                        }
                        (1, Some(p)) => p.write(data)?,
                        (2, Some(p)) if data.len() == 4 => {
                            p.resize(u16::from_be_bytes([data[0], data[1]]), u16::from_be_bytes([data[2], data[3]]))?;
                        }
                        (3, _) => {
                            let f = crypt.seal(&[3])?;
                            wtx.send(WsMsg::Binary(bytes::Bytes::from(f))).await?;
                        }
                        _ => {}
                    }
                }
                Some(Ok(WsMsg::Text(t))) if t.as_str().contains("peer-left") => return Ok(()),
                Some(Ok(WsMsg::Close(_))) | Some(Err(_)) | None => return Ok(()),
                Some(Ok(_)) => {}
            },
            chunk = out => match chunk {
                Some(b) => {
                    let mut plain = Vec::with_capacity(1 + b.len());
                    plain.push(1);
                    plain.extend_from_slice(&b);
                    let f = crypt.seal(&plain)?;
                    wtx.send(WsMsg::Binary(bytes::Bytes::from(f))).await?;
                }
                None => {
                    // shell exited: tell the phone, then end
                    *pty = None;
                    let f = crypt.seal(&[4])?;
                    let _ = wtx.send(WsMsg::Binary(bytes::Bytes::from(f))).await;
                    return Ok(());
                }
            },
        }
    }
}

#[cfg(test)]
mod ws_crypto_tests {
    use super::*;

    #[test]
    fn hkdf_matches_rfc5869_case1() {
        let ikm = [0x0bu8; 22];
        let salt: Vec<u8> = (0x00..=0x0c).collect();
        let info: Vec<u8> = (0xf0..=0xf9).collect();
        // First 32 bytes of the RFC 5869 test case 1 OKM.
        assert_eq!(
            hex::encode(hkdf32(&ikm, &salt, &info)),
            "3cb25f25faacd57a90434f64d0362f2a2d2d0a90cf1a5a4c5db02d56ecc4c5bf"
        );
    }

    #[test]
    fn frames_roundtrip_and_reject_tampering_replay_and_wrong_token() {
        let (cn, hn) = ([1u8; 16], [2u8; 16]);
        let mut host = Crypt::new("tokentokentoken", &cn, &hn, true).unwrap();
        let mut phone = Crypt::new("tokentokentoken", &cn, &hn, false).unwrap();

        let f0 = phone.seal(b"\x01ls\r").unwrap();
        assert_eq!(host.open(&f0).unwrap(), b"\x01ls\r");
        let f1 = host.seal(b"\x01output").unwrap();
        assert_eq!(phone.open(&f1).unwrap(), b"\x01output");

        assert!(host.open(&f0).is_err(), "replay must be rejected");

        let mut bad = phone.seal(b"\x01x").unwrap();
        *bad.last_mut().unwrap() ^= 1;
        assert!(host.open(&bad).is_err(), "tampering must be rejected");

        let mut other = Crypt::new("a-different-token", &cn, &hn, true).unwrap();
        let f = phone.seal(b"\x01y").unwrap();
        assert!(other.open(&f).is_err(), "wrong token must fail");
    }
}

async fn connect_ws(url: &str) -> Result<tokio_tungstenite::WebSocketStream<tokio_tungstenite::MaybeTlsStream<tokio::net::TcpStream>>> {
    let mut last = None;
    for _ in 0..20 {
        match tokio_tungstenite::connect_async(url).await {
            Ok((ws, _)) => return Ok(ws),
            Err(e) => {
                last = Some(e);
                tokio::time::sleep(Duration::from_millis(150)).await;
            }
        }
    }
    Err(anyhow!("cannot reach signaling server: {}", last.unwrap()))
}
/// Console children of a GUI program (the tray exe) would each pop up a console window: suppress it.
#[cfg(windows)]
fn no_window_std(c: &mut std::process::Command) -> &mut std::process::Command {
    use std::os::windows::process::CommandExt;
    c.creation_flags(0x0800_0000) // CREATE_NO_WINDOW
}
#[cfg(not(windows))]
fn no_window_std(c: &mut std::process::Command) -> &mut std::process::Command {
    c
}
fn no_window(c: &mut tokio::process::Command) -> &mut tokio::process::Command {
    #[cfg(windows)]
    c.creation_flags(0x0800_0000); // CREATE_NO_WINDOW
    c
}

/// Locate the `devtunnel` CLI (PATH first, then the WinGet links folder, which is often not on PATH).
fn devtunnel_exe() -> std::path::PathBuf {
    if let Some(dir) = std::env::var_os("LOCALAPPDATA") {
        let p = std::path::Path::new(&dir).join(r"Microsoft\WinGet\Links\devtunnel.exe");
        if p.exists() && no_window_std(std::process::Command::new("devtunnel").arg("--version")).output().is_err() {
            return p;
        }
    }
    "devtunnel".into()
}

/// First `https://` URL in `line` that points at `port` (`https://<id>-<port>.<region>.devtunnels.ms`).
fn tunnel_url(line: &str, port: u16) -> Option<String> {
    let marker = format!("-{port}.");
    line.split(|c: char| c.is_whitespace() || c == ',')
        .find(|t| t.starts_with("https://") && t.contains(&marker))
        .map(|t| t.trim_end_matches('/').to_string())
}

/// Run `devtunnel <args>` to completion; returns (success, stdout+stderr).
async fn dt(args: &[&str]) -> Result<(bool, String)> {
    let out = no_window(tokio::process::Command::new(devtunnel_exe()).args(args))
        .stdin(std::process::Stdio::null())
        .output()
        .await
        .context("cannot run `devtunnel` (install: winget install Microsoft.devtunnel, then `devtunnel user login`)")?;
    let text = format!("{}\n{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr));
    Ok((out.status.success(), text.trim().to_string()))
}

/// The last few non-empty lines of CLI output, for error messages.
fn tail(s: &str) -> String {
    let v: Vec<&str> = s.lines().map(str::trim).filter(|l| !l.is_empty()).collect();
    v[v.len().saturating_sub(3)..].join(" | ")
}

/// Host the project's single persistent Dev Tunnel `id` on `port` (created on first use, reused
/// afterwards, so runs never pile up new tunnels). Without `anonymous`, visitors must sign in as the
/// tunnel owner (the account `devtunnel user login` used); the access rules are re-applied on every
/// start so the setting always matches the flag. The returned child stops the hosting when dropped.
async fn start_devtunnel(port: u16, anonymous: bool, id: &str) -> Result<(tokio::process::Child, String)> {
    use tokio::io::{AsyncBufReadExt, BufReader};
    let port_s = port.to_string();

    let (exists, _) = dt(&["show", id]).await?;
    if !exists {
        eprintln!("tunnel: creating persistent tunnel '{id}' (one-time)");
        let (ok, out) = dt(&["create", id, "-e", "30d", "-d", "terminal-tunnel (phone shell)"]).await?;
        if !ok {
            let hint = if out.to_lowercase().contains("limit") {
                "too many tunnels on this account: wait for old ones to expire, or delete them with `devtunnel list` / `devtunnel delete <id>`"
            } else {
                "not logged in? run `devtunnel user login`; or set TT_DEVTUNNEL_ID to another name"
            };
            bail!("devtunnel create {id} failed: {} ({hint})", tail(&out));
        }
    }
    let (ok, out) = dt(&["port", "create", id, "-p", &port_s]).await?;
    if !ok && !out.to_lowercase().contains("exist") {
        bail!("devtunnel port create failed: {}", tail(&out));
    }
    if anonymous {
        let (ok, out) = dt(&["access", "create", id, "--anonymous"]).await?;
        if !ok && !out.to_lowercase().contains("exist") {
            bail!("devtunnel access create --anonymous failed: {}", tail(&out));
        }
    } else {
        // Back to the default: only the owner can connect. Never continue if this fails.
        let (ok, out) = dt(&["access", "reset", id]).await?;
        if !ok {
            bail!("could not enforce sign-in on the tunnel: {}", tail(&out));
        }
    }

    let mut child = no_window(tokio::process::Command::new(devtunnel_exe()).args(["host", id]))
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::piped())
        .kill_on_drop(true)
        .spawn()
        .context("cannot run `devtunnel`")?;
    // Merge stdout and stderr into one stream of lines; the readers keep draining so the tunnel
    // process never blocks on a full pipe.
    let (tx, mut rx) = mpsc::unbounded_channel::<String>();
    let (out, err) = (child.stdout.take().context("no stdout")?, child.stderr.take().context("no stderr")?);
    for stream in [Box::new(out) as Box<dyn tokio::io::AsyncRead + Unpin + Send>, Box::new(err)] {
        let tx = tx.clone();
        tokio::spawn(async move {
            let mut lines = BufReader::new(stream).lines();
            while let Ok(Some(l)) = lines.next_line().await {
                let _ = tx.send(l);
            }
        });
    }
    drop(tx);
    let mut seen = Vec::new();
    let url = tokio::time::timeout(Duration::from_secs(30), async {
        while let Some(line) = rx.recv().await {
            if let Some(u) = tunnel_url(&line, port) {
                return Ok(u);
            }
            seen.push(line);
        }
        Err(anyhow!("devtunnel exited before reporting a URL: {}", tail(&seen.join("\n"))))
    })
    .await
    .map_err(|_| anyhow!("timed out waiting for devtunnel"))??;
    Ok((child, url))
}

/// The long-lived part of hosting: the relay server and (optionally) the Dev Tunnel. Created once;
/// many sessions (rooms) can then be opened on it.
struct Prepared {
    /// Public base URL put in the link (https).
    base: String,
    /// Where the host itself reaches the relay (the public URL may require a login).
    host_base: Option<String>,
    /// Keeps the `devtunnel host` process alive; dropping it stops the hosting.
    _tunnel: Option<tokio::process::Child>,
}

async fn prepare(signal: Option<String>, port: u16, devtunnel: bool, tunnel_anonymous: bool, tunnel_id: &str) -> Result<Prepared> {
    let mut tunnel = None;
    let mut host_base: Option<String> = None;
    let base = match signal {
        Some(s) => s.trim_end_matches('/').to_string(),
        None if devtunnel => {
            // Only the tunnel needs to reach the embedded server: keep it off the LAN.
            tokio::spawn(async move {
                if let Err(e) = run_signal(port, "127.0.0.1").await {
                    eprintln!("signaling server: {e:#}");
                }
            });
            let (child, url) = start_devtunnel(port, tunnel_anonymous, tunnel_id).await?;
            tunnel = Some(child);
            host_base = Some(format!("http://127.0.0.1:{port}"));
            eprintln!(
                "tunnel: {}",
                if tunnel_anonymous { "ANONYMOUS (anyone with the URL can load the page)" } else { "sign-in required (owner account only)" }
            );
            url
        }
        None => bail!("host-web needs an https link: use --devtunnel, or --signal https://<your signaling server>"),
    };
    // The browser's WebCrypto (used for the end-to-end encryption) only exists on https pages and
    // on localhost.
    let secure_page = base.starts_with("https://") || base.contains("://127.0.0.1") || base.contains("://localhost");
    if !secure_page {
        bail!("the signaling link must be https (WebCrypto is unavailable on plain http): use --devtunnel or an https --signal");
    }
    Ok(Prepared { base, host_base, _tunnel: tunnel })
}

/// Open a fresh single-use room on the relay. Returns the host's socket, the token and the link.
async fn open_room(p: &Prepared) -> Result<(HostWs, String, String)> {
    let room = rand_hex(8)?;
    let token = rand_hex(16)?;
    let ws_url = format!("{}/ws/{room}/host", p.host_base.as_deref().unwrap_or(&p.base).replacen("http", "ws", 1));
    let ws = connect_ws(&ws_url).await?;
    // The token lives in the URL fragment, which browsers never send to any server.
    let url = format!("{}/w/{room}#{token}", p.base);
    Ok((ws, token, url))
}

/// One session in the console: print the QR, wait for the phone, end when the session ends.
pub async fn host_web(shell: String, root: Option<std::path::PathBuf>, signal: Option<String>, port: u16, devtunnel: bool, tunnel_anonymous: bool, tunnel_id: String) -> Result<()> {
    let p = prepare(signal, port, devtunnel, tunnel_anonymous, &tunnel_id).await?;
    let (ws, token, url) = open_room(&p).await?;
    println!("Scan with the iPhone camera (single-use link, gives a shell on this machine):\n");
    print_qr(&url)?;
    println!("\n{url}\n\nWaiting for browser...");

    let mut pty = None;
    tokio::select! {
        r = ws_session(ws, &token, &shell, root.as_deref(), None, &mut pty) => { println!("session ended"); r }
        _ = tokio::signal::ctrl_c() => { println!(); Ok(()) }
    }
}

/// Tray mode (Windows): keep the tunnel and relay up and live in the notification area. Each session
/// gets a fresh single-use link (shown as a QR window / copied from the menu); when a session ends a
/// new link is created automatically, so nothing needs restarting. Quit from the tray menu.
#[cfg(windows)]
pub async fn host_tray(shell: String, root: Option<std::path::PathBuf>, signal: Option<String>, port: u16, devtunnel: bool, tunnel_anonymous: bool, tunnel_id: String, hide_console: bool) -> Result<()> {
    use crate::tray::{self, Command};

    if hide_console {
        // Detach from the console so no terminal window stays open for the background app.
        unsafe {
            let _ = windows::Win32::System::Console::FreeConsole();
        }
    }
    let (cmd_tx, mut cmd_rx) = mpsc::unbounded_channel::<Command>();
    let tray = tray::spawn(cmd_tx);
    tray.update(|v| v.status = "Starting (tunnel and relay)...".into());

    let p = match prepare(signal, port, devtunnel, tunnel_anonymous, &tunnel_id).await {
        Ok(p) => p,
        Err(e) => {
            // The caller reports the error (message box in the GUI program, stderr in the console one).
            tray.quit();
            return Err(e);
        }
    };

    let mut first = true;
    let mut pty: Option<crate::pty::Pty> = None; // the shell outlives phone connections
    let mut next: Option<(HostWs, String, String)> = None; // fresh link opened while a phone is connected
    loop {
        let opened = match next.take() {
            Some(x) => Ok(x),
            None => open_room(&p).await,
        };
        let (ws, token, url) = match opened {
            Ok(x) => x,
            Err(e) => {
                tray.set_link(None);
                tray.update(|v| v.status = format!("Cannot open a session: {e:#}. Retrying..."));
                tokio::select! {
                    _ = tokio::time::sleep(Duration::from_secs(5)) => continue,
                    c = cmd_rx.recv() => if matches!(c, Some(Command::Quit) | None) { tray.quit(); return Ok(()) } else { continue },
                }
            }
        };
        tray.set_link(Some(url));
        tray.update(|v| v.status = "Waiting for the phone: scan the QR code".into());
        if first {
            tray.show();
            first = false;
        } else {
            tray.notify("New link ready", "Click the tray icon to show the QR code.");
        }

        enum Outcome {
            Ended(Result<()>),
            Restart,
            Quit,
        }
        let (ev_tx, mut ev_rx) = mpsc::unbounded_channel::<SessionEvent>();
        let outcome = {
        let session = ws_session(ws, &token, &shell, root.as_deref(), Some(ev_tx), &mut pty);
        tokio::pin!(session);
        loop {
            tokio::select! {
                r = &mut session => break Outcome::Ended(r),
                Some(ev) = ev_rx.recv() => match ev {
                    SessionEvent::Authenticated { code } => {
                        // The phone used up its link: show a different, fresh one right away.
                        match open_room(&p).await {
                            Ok((w2, t2, u2)) => {
                                tray.set_link(Some(u2.clone()));
                                next = Some((w2, t2, u2));
                            }
                            Err(_) => tray.set_link(None),
                        }
                        tray.update(|v| v.status = format!("Phone connected. Match code {code}. New link ready"));
                        tray.notify("Phone connected", &format!("Match code {code}: compare it with the phone."));
                    }
                },
                c = cmd_rx.recv() => match c {
                    Some(Command::NewSession) => break Outcome::Restart,
                    Some(Command::Quit) | None => break Outcome::Quit,
                },
            }
        }
        };
        match outcome {
            Outcome::Quit => {
                tray.quit();
                return Ok(());
            }
            Outcome::Restart => tray.update(|v| v.status = "Creating a new link...".into()),
            Outcome::Ended(Ok(())) => tray.update(|v| v.status = if pty.is_some() { "Phone disconnected: shell keeps running".into() } else { "Session ended".into() }),
            Outcome::Ended(Err(e)) => {
                tray.update(|v| v.status = format!("Session ended: {e:#}"));
                tray.notify("Session ended", &format!("{e:#}"));
                tokio::time::sleep(Duration::from_secs(2)).await; // avoid a tight loop on repeated failures
            }
        }
    }
}
