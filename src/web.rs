const XTERM_JS: &str = include_str!("web/vendor/xterm.min.js");
const XTERM_FIT_JS: &str = include_str!("web/vendor/xterm-addon-fit.min.js");
const XTERM_CSS: &str = include_str!("web/vendor/xterm.min.css");
